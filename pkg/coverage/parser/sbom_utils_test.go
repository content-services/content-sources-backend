func parseTestdata(t *testing.T, parseName, testdataPath string) *ParseResult {
	t.Helper()
	f, err := os.Open(filepath.Join("fixtures", testdataPath))
	require.NoError(t, err)
	t.Cleanup(func() { _ = f.Close() })

	result, err := Parse(parseName, f)
	require.NoError(t, err)
	return result
}

func TestSniffFormat(t *testing.T) {
	tests := []struct {
		path string
		want string
	}{
		{filepath.Join("fixtures", "cyclonedx", "bom.json"), FormatCycloneDX},
		{filepath.Join("fixtures", "cyclonedx", "tools.cdx.xml"), FormatCycloneDX},
		{filepath.Join("fixtures", "spdx", "v2.json"), FormatSPDX},
		{filepath.Join("fixtures", "spdx", "v3.json"), FormatSPDX},
		{filepath.Join("fixtures", "spdx", "tagvalue.spdx"), FormatSPDX},
	}
	for _, tt := range tests {
		t.Run(tt.path, func(t *testing.T) {
			f, err := os.Open(tt.path)
			require.NoError(t, err)
			defer f.Close()

			got, err := sniffFormat(bufio.NewReader(f))
			require.NoError(t, err)
			assert.Equal(t, tt.want, got)
		})
	}
}

func TestSniffFormat_POM(t *testing.T) {
	tests := []struct {
		name string
		data string
		want string
	}{
		{
			name: "Maven namespace",
			data: `<?xml version="1.0" encoding="UTF-8"?>
<!-- generated by Maven -->
<project xmlns="http://maven.apache.org/POM/4.0.0">
  <modelVersion>4.0.0</modelVersion>
</project>`,
			want: FormatPOM,
		},
		{
			name: "model version without namespace",
			data: `<project><modelVersion>4.0.0</modelVersion></project>`,
			want: FormatPOM,
		},
		{
			name: "projects wrapper",
			data: `<projects><project><modelVersion>4.0.0</modelVersion></project></projects>`,
			want: FormatPOM,
		},
		{
			name: "projects wrapper with Maven namespace",
			data: `<projects xmlns="http://maven.apache.org/POM/4.0.0"><project/></projects>`,
			want: FormatPOM,
		},
		{
			name: "unrelated project XML",
			data: `<project><name>not a Maven POM</name></project>`,
		},
		{
			name: "unrelated projects XML",
			data: `<projects><project><name>not a Maven POM</name></project></projects>`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			format, err := sniffFormat(bufio.NewReader(strings.NewReader(tt.data)))
			require.NoError(t, err)
			assert.Equal(t, tt.want, format)
		})
	}
}

func TestSniffFormat_DoesNotConsumeInput(t *testing.T) {
	data := `<project><modelVersion>4.0.0</modelVersion></project>`
	r := bufio.NewReader(strings.NewReader(data))

	_, err := sniffFormat(r)
	require.NoError(t, err)

	remaining, err := io.ReadAll(r)
	require.NoError(t, err)
	assert.Equal(t, data, string(remaining))
}

func TestPeekSBOMStart(t *testing.T) {
	start, err := peekSBOMStart(bufio.NewReader(strings.NewReader("  \n{")))
	require.NoError(t, err)
	assert.Equal(t, byte('{'), start)
}

func TestDiscardUTF8BOM(t *testing.T) {
	r := bufio.NewReader(bytes.NewReader(append([]byte{0xEF, 0xBB, 0xBF}, '{')))
	discardUTF8BOM(r)
	b, err := r.ReadByte()
	require.NoError(t, err)
	assert.Equal(t, byte('{'), b)
}

func TestReadJSONObject_SkipsUnknownFields(t *testing.T) {
	raw := `{"files":[{"fileName":"a.py"},{"fileName":"b.py"}],"name":"flask"}`
	dec := json.NewDecoder(strings.NewReader(raw))
	var name string
	err := readJSONObject(dec, map[string]jsonFieldHandler{
		"name": func(d *json.Decoder) error { return decodeJSONString(d, &name) },
	})
	require.NoError(t, err)
	assert.Equal(t, "flask", name)
}

func TestHasAnySuffix(t *testing.T) {
	assert.True(t, hasAnySuffix("app.cdx.json", ".cdx.json", ".cdx.xml"))
	assert.False(t, hasAnySuffix("app.cdx.yml", ".cdx.json", ".cdx.xml"))
}
